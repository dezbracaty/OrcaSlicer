"""Pin the original compatibility tree and whitelist only its GUI adaptations.

This checks the producer/version tree, not the whole import workflow. Native
model/config comparisons and implementation review cover the remaining stages.
"""
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess
import textwrap

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "src/libslicer_api/orca"
BEGIN = "// ORCA_PROJECT_COMPATIBILITY_BEGIN"
END = "// ORCA_PROJECT_COMPATIBILITY_END"


def normalize(text):
    return textwrap.dedent("\n".join(line.rstrip() for line in text.splitlines())).strip() + "\n"


def adapt_gui_access(text):
    # No branch, threshold, setting assignment, or configuration cleanup is
    # rewritten. Only local names, dialog construction, and GUI diagnostics.
    for old, new in {
        "en_3mf_file_type": "type", "file_version": "version",
        "config_loaded": "loaded", "config_substitutions": "substitutions",
        "load_type != LoadType::LoadGeometry": "request.mode != ProjectReadMode::Geometry",
    }.items():
        text = text.replace(old, new)
    # The original DynamicConfig::opt_string / unchecked option dereferences
    # null for a corrupt alpha project missing these keys. Preserve its branch
    # and assignments, but turn that undefined access into a read error.
    text = text.replace('loaded.opt_string("sparse_infill_rotate_template")', 'rotation_template()')
    text = text.replace('loaded.option<ConfigOptionEnum<InfillPattern>>("sparse_infill_pattern")->value', 'infill_pattern()')
    text, count = re.subn(
        r'wxString msg_text = _\([\s\S]+?if \(dialog.ShowModal\(\) == wxID_YES\) \{',
        'if (ask(ProjectDecisionKind::LegacyInfillRotation, "legacy_infill_rotation_fix", '
        '"Clear the legacy OrcaSlicer 2.3.1-alpha infill rotation template?")) {', text)
    assert count == 2, "Original rotation dialogs changed"
    pattern = (r'wxString text\s*= wxString::Format\([\s\S]+?'
               r'log_and_show_3mf_info\((?:context|text), (newer_3mf_title|bambu_project_title)\);')
    def version_diagnostic(match):
        code = "project.newer_version" if match[1] == "newer_3mf_title" else "project.bambu_version"
        return f'diagnostic("{code}", "The 3MF version may not be fully compatible.", version.to_string());'
    text, count = re.subn(pattern, version_diagnostic, text)
    assert count == 4, "Original version diagnostics changed"
    text, count = re.subn(
        r'wxString text = _L\("The 3MF was created by BambuStudio\. Some settings may differ from OrcaSlicer\."\);\s*'
        r'log_and_show_3mf_info\(text, bambu_project_title\);',
        'diagnostic("project.bambu_version", "The 3MF was created by BambuStudio. Some settings may differ from OrcaSlicer.", {}, "info");', text)
    assert count == 1
    messages = {
        "msg_unsupported_geometry": "The 3MF is not supported by OrcaSlicer, loading geometry data only.",
        "msg_old_orca_geometry": "The 3MF file was generated by an old OrcaSlicer version, loading geometry data only.",
        "msg_older_geometry": "The 3MF file was generated by an older version, loading geometry data only.",
        "msg_bambu_geometry": "The 3MF file was generated by BambuStudio, loading geometry data only.",
    }
    for name, message in messages.items():
        text = text.replace(f'log_and_show_3mf_info({name}, load_3mf_title);',
                            f'diagnostic("project.geometry_fallback", "{message}", {{}}, "info");')
    text, count = re.subn(r'        BOOST_LOG_TRIVIAL\(info\)[\s\S]+?% path.string\(\);\n', "", text)
    assert count == 1
    assert not any(word in text for word in ("wxString", "wxGetApp", "MessageDialog", "log_and_show_3mf_info"))
    return normalize(text)


def original_body():
    copied = (SOURCE / "ProjectImportCompatibility.original.inc").read_text(encoding="utf-8")
    return normalize(copied[copied.index("if (en_3mf_file_type"):])


def main():
    origin = json.loads((SOURCE / "project_import_origin.json").read_text(encoding="utf-8"))
    copied = original_body()
    assert hashlib.sha256(copied.encode()).hexdigest() == origin["sha256_normalized_body"]
    if shutil.which("git"):
        original = subprocess.run(["git", "-C", str(ROOT), "show", f'{origin["revision"]}:{origin["path"]}'],
                                  capture_output=True, check=False)
        if original.returncode == 0:
            text = original.stdout.decode("utf-8").replace("\r\n", "\n")
            start = text.index(origin["start"])
            assert copied == normalize(text[start:text.index(origin["end_exclusive"], start)])
    production = (ROOT / "src/libslicer_api/Library.cpp").read_text(encoding="utf-8")
    assert production.count(BEGIN) == production.count(END) == 1
    region = production.split(BEGIN, 1)[1].split(END, 1)[0]
    assert normalize(region) == adapt_gui_access(copied), "Compatibility rules exceed the explicit GUI adaptation"
    print("Original 3MF compatibility branches and explicit GUI adaptations verified:", origin["revision"])


if __name__ == "__main__":
    main()
